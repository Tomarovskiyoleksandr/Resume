const setText = (selector, value) => {
    document.querySelectorAll(selector).forEach((element) => {
        element.textContent = value;
    });
};

const setHtml = (selector, value) => {
    document.querySelectorAll(selector).forEach((element) => {
        element.innerHTML = value;
    });
};

const applyLanguage = (language) => {
    const dictionary = translations[language] || translations.en;

    document.documentElement.lang = language;

    textBindings.forEach(([selector, key]) => setText(selector, dictionary[key]));
    htmlBindings.forEach(([selector, key]) => setHtml(selector, dictionary[key]));

    document.querySelectorAll(".project__status").forEach((element) => {
        element.textContent = dictionary.projectStatus;
    });

    setText(".section3__card:nth-child(1) .project__type", dictionary.projectTypeApp);
    setText(".section3__card:nth-child(2) .project__type", dictionary.projectTypeSite);
    setText(".section3__card:nth-child(3) .project__type", dictionary.projectTypeApp);

    const nextLanguage = languageOrder[(languageOrder.indexOf(language) + 1) % languageOrder.length];
    const button = document.querySelector("#LG_BTN");

    if (button) {
        button.textContent = languageLabels[nextLanguage];
        button.dataset.currentLanguage = language;
        button.setAttribute("aria-label", `Change language to ${languageLabels[nextLanguage]}`);
    }

    localStorage.setItem("pageLanguage", language);
};

document.addEventListener("DOMContentLoaded", () => {
    const button = document.querySelector("#LG_BTN");
    const savedLanguage = localStorage.getItem("pageLanguage");
    const browserLanguage = navigator.language.slice(0, 2);
    const startLanguage = languageOrder.includes(savedLanguage)
        ? savedLanguage
        : languageOrder.includes(browserLanguage)
            ? browserLanguage
            : "en";

    applyLanguage(startLanguage);

    if (!button) {
        return;
    }

    button.addEventListener("click", (event) => {
        event.preventDefault();

        const currentLanguage = button.dataset.currentLanguage || startLanguage;
        const nextLanguage = languageOrder[(languageOrder.indexOf(currentLanguage) + 1) % languageOrder.length];

        applyLanguage(nextLanguage);
    });
});
